"""Generate the docs that come from the code, or check that they are current.

    uv run --no-sync python -m tools.docs           # write them
    uv run --no-sync python -m tools.docs --check   # fail when one is out of date

Three things are generated:

- ``docs/cli.md``, the CLI reference, from the command definitions;
- ``docs/json.md``, the JSON schema reference, from the payload schemas;
- the evidence block in ``README.md``: real output of wm, run on a small
  generic change in a scratch folder with fixed dates, so it never drifts.
"""

import argparse
import datetime
import json
import os
import subprocess
import sys
import tempfile
from collections.abc import Iterator
from contextlib import contextmanager
from pathlib import Path
from typing import Any

from waymark import __version__, cli
from waymark.services import lifecycle, setup
from waymark.views import payloads, render
from waymark.views.schemas import SCHEMAS
from waymark.views.style import Style

ROOT = Path(__file__).resolve().parent.parent
CLI_DOC = ROOT / "docs" / "cli.md"
JSON_DOC = ROOT / "docs" / "json.md"
README = ROOT / "README.md"
EVIDENCE_START = "<!-- generated: evidence -->"
EVIDENCE_END = "<!-- end of generated evidence -->"
GENERATED = "<!-- Generated by tools/docs.py from the code. Don't edit it by hand. -->"

DAY = datetime.date(2026, 1, 15)
OWNER = "Alex Example"
CHANGE = "add-result-limit"


# The CLI reference -------------------------------------------------------------------------


def _subparsers(parser: argparse.ArgumentParser) -> "argparse._SubParsersAction[Any] | None":
    return next(
        (a for a in parser._actions if isinstance(a, argparse._SubParsersAction)),
        None,
    )


def _usage(prog: str, parser: argparse.ArgumentParser) -> str:
    parts = [prog]
    for action in parser._actions:
        if isinstance(action, argparse._HelpAction | argparse._SubParsersAction):
            continue
        if action.option_strings:
            flag = max(action.option_strings, key=len)
            value = "" if action.nargs == 0 else f" {action.metavar or action.dest.upper()}"
            text = f"{flag}{value}"
            parts.append(text if action.required else f"[{text}]")
        else:
            name = action.metavar or action.dest
            if action.choices and not action.metavar:
                name = "|".join(str(choice) for choice in action.choices)
            parts.append(f"[{name}]" if action.nargs == "?" else f"<{name}>")
    sub = _subparsers(parser)
    if sub is not None:
        parts.append("<command>")
    return " ".join(parts)


def _arguments(parser: argparse.ArgumentParser) -> list[str]:
    lines = []
    for action in parser._actions:
        if isinstance(action, argparse._HelpAction | argparse._SubParsersAction):
            continue
        name = ", ".join(f"`{flag}`" for flag in action.option_strings) or f"`{action.dest}`"
        detail = action.help or ""
        if action.choices:
            detail += (
                ("; " if detail else "")
                + "one of "
                + ", ".join(f"`{choice}`" for choice in action.choices)
            )
        if action.required and action.option_strings:
            detail += " (required)"
        lines.append(f"- {name}: {detail}".rstrip())
    return lines


def _commands(
    parser: argparse.ArgumentParser, prog: str
) -> Iterator[tuple[str, argparse.ArgumentParser]]:
    sub = _subparsers(parser)
    if sub is None:
        return
    for name, child in sub.choices.items():
        full = f"{prog} {name}"
        yield full, child
        yield from _commands(child, full)


def cli_reference() -> str:
    """The CLI reference, from the command definitions."""
    parser = cli.build_parser()
    lines = [
        "# CLI reference",
        "",
        GENERATED,
        "",
        f"Every command of `wm` {__version__.split('.dev')[0]}. Read commands take `--json`; "
        "their payloads are described in the [JSON schema reference](json.md).",
        "",
        "Exit codes: `0` success; `1` refused, or problems found; `2` usage error.",
    ]
    for full, child in _commands(parser, "wm"):
        lines += ["", f"## {full}", "", child.description or "", "", "```"]
        lines += [_usage(full, child), "```"]
        arguments = _arguments(child)
        if arguments:
            lines += ["", *arguments]
    return "\n".join(lines) + "\n"


# The JSON schema reference -----------------------------------------------------------------


def json_reference() -> str:
    """The JSON schema reference, from the payload schemas."""
    lines = [
        "# JSON schema reference",
        "",
        GENERATED,
        "",
        "Every read command takes `--json`. Each payload starts with `schema` (its name) and "
        "`version`. Adding a field keeps the version; removing or changing one raises it. "
        "Payloads hold no absolute paths and are written with ASCII escapes.",
        "",
        "| Schema | Version | Printed by |",
        "|---|---|---|",
    ]
    sources = {
        "status": "`wm status`",
        "inbox": "`wm inbox`",
        "ls": "`wm ls`",
        "check": "`wm check`",
        "show.change": "`wm show` for a change",
        "show.spec": "`wm show` for a spec",
        "show.milestone": "`wm show` for a milestone",
        "show.exploration": "`wm show` for an exploration",
        "instructions": "`wm instructions`",
        "context.explore": "`wm context --for explore`",
        "context.implement": "`wm context <change> <item> --for implement`",
        "context.review": "`wm context <change> <item> --for review`",
        "doctor": "`wm doctor`, `wm atlas doctor`",
        "pr": "`wm pr`",
    }
    assert set(sources) == set(SCHEMAS), "every schema needs a line in the table"
    for name, schema in SCHEMAS.items():
        version = schema["properties"]["version"]["const"]
        lines.append(f"| [`wm.{name}`](#wm{name.replace('.', '')}) | {version} | {sources[name]} |")
    for name, schema in SCHEMAS.items():
        text = json.dumps(schema, indent=2, ensure_ascii=True)
        lines += [
            "",
            f"## wm.{name}",
            "",
            f"Printed by {sources[name]}.",
            "",
            "```json",
            text,
            "```",
        ]
    return "\n".join(lines) + "\n"


# The README's evidence ---------------------------------------------------------------------

PROPOSAL = """# Add a result limit

Owner: {owner}
Path: short

## Why

Searches that match thousands of documents return all of them, and the page slows down.

## What changes

A search returns at most fifty results.

## Non-goals

Paging through more results.

## Impact

Specs: search.
"""

DELTA = """# Search

## Purpose

How a search finds and returns documents.

## Added requirements

### Requirement: Result limit
A search SHALL return at most fifty results.

#### Scenario: Many matches
- GIVEN an index where a query matches more than fifty documents
- WHEN the search runs
- THEN fifty results come back
"""

TASKS = """# Tasks

## 1. Limit

- [ ] 1.1 Cap the result count
  - Criteria: at most fifty results come back
  - Verify: a test searches an index with fifty-one matches
- [ ] 1.2 Mention the limit in the help text   `review: none`
  - Criteria: the search help names the limit
"""


@contextmanager
def _scratch() -> Iterator[Path]:
    """A scratch git repository, with this machine's git and wm settings kept out."""
    saved = dict(os.environ)
    with tempfile.TemporaryDirectory() as folder:
        os.environ["GIT_CONFIG_GLOBAL"] = os.devnull
        os.environ["GIT_CONFIG_NOSYSTEM"] = "1"
        os.environ["WAYMARK_REGISTRY"] = str(Path(folder) / "registry.toml")
        root = Path(folder) / "search"
        subprocess.run(["git", "init", "--quiet", str(root)], check=True)
        subprocess.run(["git", "-C", str(root), "config", "user.name", OWNER], check=True)
        try:
            yield root
        finally:
            os.environ.clear()
            os.environ.update(saved)


def _write(root: Path, relative: str, text: str) -> None:
    path = root / "waymark" / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))


def _tree(root: Path, folder: str) -> list[str]:
    base = root / "waymark" / folder
    return sorted(path.relative_to(root).as_posix() for path in base.rglob("*") if path.is_file())


def evidence() -> str:
    """Real wm output for a small generic change, with fixed dates."""
    style = Style(unicode=True)
    with _scratch() as root:
        setup.init_project(root, None, ("claude-code",))
        setup.create_change(root, CHANGE, short=True, owner=OWNER)
        folder = f"changes/{CHANGE}"
        _write(root, f"{folder}/proposal.md", PROPOSAL.format(owner=OWNER))
        _write(root, f"{folder}/specs/search.md", DELTA)
        _write(root, f"{folder}/tasks.md", TASKS)
        lifecycle.accept(root, CHANGE, DAY)
        lifecycle.tick(root, CHANGE, "1.1")
        lifecycle.self_review(
            root, CHANGE, "1.1", "the cap holds at fifty; the fifty-one-match test passes", DAY
        )
        from waymark.record.project import find_project  # noqa: PLC0415
        from waymark.record.record import load_record  # noqa: PLC0415

        record = load_record(find_project(root))
        status = render.to_text(payloads.status(record), style)
        files = _tree(root, folder)
        tasks = (root / "waymark" / folder / "tasks.md").read_text(encoding="utf-8")
        proposal_head = (root / "waymark" / folder / "proposal.md").read_text(encoding="utf-8")
    accepted = next(line for line in proposal_head.splitlines() if line.startswith("Accepted:"))
    lines = [
        EVIDENCE_START,
        "",
        "A small change, accepted, with its first item built and reviewed:",
        "",
        "```console",
        "$ wm status",
        status,
        "```",
        "",
        "Its task list. The tick and the review line under 1.1 were written by `wm`, "
        "not by an agent:",
        "",
        "```markdown",
        tasks.rstrip("\n"),
        "```",
        "",
        "<details>",
        "<summary>The rest of the change</summary>",
        "",
        "```",
        *files,
        "```",
        "",
        f"Your approval, written into the proposal by `wm accept`: `{accepted}`",
        "",
        "</details>",
        "",
        "<sub>Real output of this version of <code>wm</code> on a generic change, generated by "
        "<code>tools/docs.py</code>. From 0.1.1 it comes from Waymark's own record.</sub>",
        "",
        EVIDENCE_END,
    ]
    return "\n".join(lines)


def readme(current: str) -> str:
    """The README with its evidence block regenerated."""
    start = current.index(EVIDENCE_START)
    end = current.index(EVIDENCE_END) + len(EVIDENCE_END)
    return current[:start] + evidence() + current[end:]


# Running it --------------------------------------------------------------------------------


def generated() -> dict[Path, str]:
    """Every generated file, with the text it should have."""
    current = README.read_bytes().decode("utf-8")
    return {CLI_DOC: cli_reference(), JSON_DOC: json_reference(), README: readme(current)}


def stale() -> list[str]:
    """The generated files that differ from what the code produces."""
    return [
        path.relative_to(ROOT).as_posix()
        for path, text in generated().items()
        if not path.is_file() or path.read_bytes().decode("utf-8") != text
    ]


def main(argv: list[str]) -> int:
    if "--check" in argv:
        out_of_date = stale()
        for relative in out_of_date:
            print(f"{relative} is out of date. Run: uv run --no-sync python -m tools.docs")
        return 1 if out_of_date else 0
    for path, text in generated().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
        print(f"wrote {path.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
