@contextmanager
def _scratch() -> Iterator[Path]:
    """A scratch git repository, with this machine's git and wm settings kept out."""
    saved = dict(os.environ)
    with tempfile.TemporaryDirectory() as folder:
        os.environ["GIT_CONFIG_GLOBAL"] = os.devnull
        os.environ["GIT_CONFIG_NOSYSTEM"] = "1"
        os.environ["WAYMARK_REGISTRY"] = str(Path(folder) / "registry.toml")
        root = Path(folder) / "notes"
        subprocess.run(["git", "init", "--quiet", str(root)], check=True)
        subprocess.run(["git", "-C", str(root), "config", "user.name", OWNER], check=True)
        try:
            yield root
        finally:
            os.environ.clear()
            os.environ.update(saved)


def _write(root: Path, relative: str, text: str) -> None:
    path = root / "waymark" / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))


def _read(root: Path, relative: str) -> str:
    return (root / "waymark" / relative).read_bytes().decode("utf-8").rstrip("\n")


def _status(root: Path) -> str:
    from waymark.record.machine.project import find_project  # noqa: PLC0415
    from waymark.record.record import load_record  # noqa: PLC0415

    return render.to_text(payloads.status(load_record(find_project(root))), Style(unicode=True))


def _tree(root: Path, notes: dict[str, str]) -> list[str]:
    """The record's files, as an indented tree with a note beside each file that has one."""
    base = root / "waymark"
    lines = ["waymark/"]

    def walk(folder: Path, depth: int) -> None:
        for path in sorted(folder.iterdir(), key=lambda p: (p.is_dir(), p.name)):
            if path.is_dir() and not any(child.is_file() for child in path.rglob("*")):
                continue
            label = "  " * (depth + 1) + path.name + ("/" if path.is_dir() else "")
            note = notes.get(path.relative_to(base).as_posix())
            lines.append(f"{label:<46}{note}" if note else label)
            if path.is_dir():
                walk(path, depth + 1)

    walk(base, 0)
    return lines


def _file(summary: str, language: str, text: str) -> list[str]:
    return [
        "<details>",
        f"<summary>{summary}</summary>",
        "",
        f"```{language}",
        text,
        "```",
        "",
        "</details>",
    ]


def evidence() -> str:
    """A real change taken through wm from start to archive, with fixed dates."""
    folder = f"changes/{CHANGE}"
    with _scratch() as root:
        setup.init_project(root, None, ("claude-code",))
        setup.create_change(root, CHANGE, owner=OWNER)
        _write(root, f"{folder}/proposal.md", PROPOSAL.format(owner=OWNER))
        _write(root, f"{folder}/specs/appearance.md", DELTA)
        _write(root, f"{folder}/design.md", DESIGN)
        _write(root, f"{folder}/tasks.md", TASKS)
        drafted = _status(root)
        accepted = lifecycle.accept(root, CHANGE, DAY).message
        for item in ("1.1", "1.2", "1.3"):
            lifecycle.tick(root, CHANGE, item)
        lifecycle.self_review(root, CHANGE, REVIEW, DAY)
        built = _status(root)
        archived = lifecycle.archive(root, CHANGE, DAY, built=BUILT).message
        target = f"changes/archive/{DAY.isoformat()}-{CHANGE}"
        files = {
            "proposal": _read(root, f"{target}/proposal.md"),
            "design": _read(root, f"{target}/design.md"),
            "delta": _read(root, f"{target}/specs/appearance.md"),
            "tasks": _read(root, f"{target}/tasks.md"),
            "spec": _read(root, "specs/appearance.md"),
        }
        tree = _tree(
            root,
            {
                "config.toml": "settings, and the pinned wm version",
                "charter.md": "what the project is, its goals and its rules",
                "specs/appearance.md": "the living spec, now with dark mode",
                f"{target}/proposal.md": "why, what changes, and the outcome",
                f"{target}/specs/appearance.md": "the change to the spec",
                f"{target}/design.md": "how it's built, and the decisions",
                f"{target}/tasks.md": "the tasks, and what wm recorded",
            },
        )
    session = [
        "> /wm-explore People keep asking for dark mode. What would it take?",
        "",
        "> /wm-propose Let's add it: follow the device's setting, with a choice in Settings.",
        "",
        "$ wm status",
        drafted,
        "",
        f"$ wm accept {CHANGE}",
        accepted,
        "",
        "> /wm-apply",
        "",
        "$ wm status",
        built,
        "",
        "> /wm-archive",
        "",
        f'$ wm archive {CHANGE} --built "{BUILT}"',
        archived,
        "",
        "> /wm-pr",
    ]
    lines = [
        EVIDENCE_START,
        "",
        "```text",
        *session,
        "```",
        "",
        "After the archive, the record holds the new spec and the whole change, all plain",
        "markdown in your repository:",
        "",
        "```text",
        *tree,
        "```",
        "",
        *_file(f"<code>{target}/proposal.md</code>", "markdown", files["proposal"]),
        *_file(f"<code>{target}/design.md</code>", "markdown", files["design"]),
        *_file(
            f"<code>{target}/specs/appearance.md</code>, the change to the spec",
            "markdown",
            files["delta"],
        ),
        *_file(
            f"<code>{target}/tasks.md</code>, with what wm recorded", "markdown", files["tasks"]
        ),
        *_file(
            "<code>specs/appearance.md</code>, the living spec after the archive",
            "markdown",
            files["spec"],
        ),
        "",
        "<sub>Real output of this version of <code>wm</code>, generated by "
        "<code>tools/docs.py</code>.</sub>",
        "",
        EVIDENCE_END,
    ]
    return "\n".join(lines)


def readme(current: str) -> str:
    """The README with its evidence block regenerated."""
    start = current.index(EVIDENCE_START)
    end = current.index(EVIDENCE_END) + len(EVIDENCE_END)
    return current[:start] + evidence() + current[end:]


# Running it --------------------------------------------------------------------------------


def generated() -> dict[Path, str]:
    """Every generated file, with the text it should have."""
    current = README.read_bytes().decode("utf-8")
    return {CLI_DOC: cli_reference(), JSON_DOC: json_reference(), README: readme(current)}


def stale() -> list[str]:
    """The generated files that differ from what the code produces."""
    return [
        path.relative_to(ROOT).as_posix()
        for path, text in generated().items()
        if not path.is_file() or path.read_bytes().decode("utf-8") != text
    ]


def main(argv: list[str]) -> int:
    if "--check" in argv:
        out_of_date = stale()
        for relative in out_of_date:
            print(f"{relative} is out of date. Run: uv run --no-sync python -m tools.docs")
        return 1 if out_of_date else 0
    for path, text in generated().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
        print(f"wrote {path.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
